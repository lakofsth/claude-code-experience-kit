"""A word's value is bash's quote removal, and code handed on is the code bash runs.

Sentence `mh-a-words-value-is-bash-quote-removal` (hooks/tests/INVARIANTS.md), checked from the hooks/tests/INVARIANTS.md clause alone: bash itself is the oracle, every shell line run through `bash_oracle.run()`.

DIRECTIONS (each a way the sentence can be false):
  D1  '...' is literal: every printable character, a newline and a tab inside it.
  D2  an unquoted backslash escapes any character (a newline: the pair is removed; at the end of
      the text it is kept).
  D3  inside "..." and $"..." a backslash escapes only $ ` " \\ and a newline; before anything else
      it is kept.
  D4  $'...' has its escapes decoded (named, octal, hex, braced hex, \\u, \\U, \\c, unknown, NUL).
  D5  a command substitution ($(...), `...`, inside "..." or not) is kept as the code it is: each
      prints a marker under bash, and the value must hold the substitution's own text where bash
      put the marker, with the rest of the word quote-removed.
  D6  words generated by mixing D1-D5 in one word, several words to a line, so where a word ENDS
      is checked with its value.
  D7  the code handed on: a command C (printf of D6 words) quoted into ONE word W by a random mix
      of the quoting forms; `eval W`, `bash -c W` and `sh -c W` must hand on exactly C, and bash
      running C must print what bash running the original line prints.
  D7b the same through every spelling bash runs as eval (`eval --`, `builtin eval`, `command --
      eval`, ...) and `bash -c --`, and `eval W1 W2`, which runs the values joined by a space.
  D8  the command after the word is still read: `printf %s\\0 W; MARK` names MARK.
  D9  a word with no quote and no backslash is its own value, whatever expansion it holds
      ($((...)), $[...], ${...}, $x), and ends where bash's word ends.

A value check is two-stage: the generator's expected value is first checked against bash (a
mismatch there is a fault of this test and is reported as such, never as the parser's), and only
then is parse() compared with it.
"""
import os, random, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.dirname(HERE))
import bash_oracle          # noqa: E402
import bash_parse           # noqa: E402

ENV = dict(os.environ, LC_ALL="C.UTF-8", LANG="C.UTF-8")
PRINTABLE = [chr(c) for c in range(0x20, 0x7f)] + ["\t", "\n", "é"]
SAFE = "abcXYZ019_.,:=+-/%@^"              # unquoted characters with no meaning to bash


def bash_bytes(line, shell="bash"):
    p = bash_oracle.run([shell, "-c", "set -f\n" + line], capture_output=True, env=ENV, timeout=30)
    return p.returncode, p.stdout


def as_bytes(s):
    return s.encode("utf-8", "surrogateescape")


# ---- fragments: (raw text, its value under bash, its value as the sentence keeps it) ---------

def frag_plain(r):
    s = "".join(r.choice(SAFE) for _ in range(r.randint(1, 3)))
    return s, s, s


def frag_escape(r, ch=None):
    ch = ch if ch is not None else r.choice(PRINTABLE)
    v = "" if ch == "\n" else ch
    return "\\" + ch, v, v


def frag_single(r, body=None):
    if body is None:
        body = "".join(r.choice([c for c in PRINTABLE if c != "'"]) for _ in range(r.randint(0, 4)))
    return "'" + body + "'", body, body


def dq_body(r, n=None):
    raw, val = [], []
    for _ in range(n if n is not None else r.randint(0, 4)):
        if r.random() < 0.5:
            ch = r.choice(PRINTABLE)
            raw.append("\\" + ch)
            val.append("" if ch == "\n" else ch if ch in '$`"\\\n' else "\\" + ch)
        else:
            ch = r.choice([c for c in PRINTABLE if c not in '$`"\\'])
            raw.append(ch); val.append(ch)
    return "".join(raw), "".join(val)


def frag_double(r, dollar=False):
    raw, val = dq_body(r)
    return ("$" if dollar else "") + '"' + raw + '"', val, val


ANSI = [("\\a", "\a"), ("\\b", "\b"), ("\\e", "\x1b"), ("\\E", "\x1b"), ("\\f", "\f"),
        ("\\n", "\n"), ("\\r", "\r"), ("\\t", "\t"), ("\\v", "\v"), ("\\\\", "\\"), ("\\'", "'"),
        ('\\"', '"'), ("\\?", "?"), ("\\101", "A"), ("\\7G", "\aG"), ("\\044", "$"), ("\\x24", "$"),
        ("\\x4G", "\x04G"), ("\\x{24}", "$"), ("\\x{263a}", ":"), ("\\u263a", "☺"),
        ("\\U0001F600", "\U0001F600"), ("\\u41G", "AG"), ("\\cA", "\x01"), ("\\ca", "\x01"),
        ("\\c?", "\x7f"), ("\\c[", "\x1b"), ("\\q", "\\q"), ("\\z", "\\z"), ("\\8", "\\8"),
        ("\\%", "\\%"), ("\\ ", "\\ "), ("\\xg", "\\xg"), ("\\xc3\\xa9", "é")]


def frag_ansi(r):
    raw, val, nul = [], [], False
    for _ in range(r.randint(0, 4)):
        k = r.random()
        if k < 0.5:
            a, b = r.choice(ANSI)
        elif k < 0.55:
            a, b = r.choice(["\\0", "\\x00", "\\c@"]), "\x00"
        else:
            a = r.choice([c for c in PRINTABLE if c not in "'\\"]); b = a
        raw.append(a)
        if not nul:
            if "\x00" in b:
                nul = True; b = b[:b.index("\x00")]
            val.append(b)
    v = "".join(val)
    return "$'" + "".join(raw) + "'", v, v


SUB_BODIES = ["printf %s {M}", "printf %s '{M}'", 'printf %s "{M}"', ": ')'; printf %s {M}",
              "case x in x) printf %s {M};; esac", "printf %s {M} # )\n",
              "printf %s \"$(printf %s {M})\"", "{{ printf %s {M}; }}", "printf %s {M} | cat"]


def frag_sub(r, k, in_dq=False):
    """A substitution that prints marker k: (raw as written in its context, the bash value, the
    kept text). In "..." a backtick body has \\" for each ", which bash removes."""
    mk = "Mk%dq" % k
    body = r.choice(SUB_BODIES).format(M=mk)
    if r.random() < 0.5 or "`" in body or "$(" in body:
        raw = "$(" + body + ")"
        kept = raw
    else:
        b2 = body.replace("\\", "\\\\").replace("$", "\\$")
        if in_dq:
            raw = "`" + b2.replace('"', '\\"') + "`"
            kept = "`" + b2 + "`"
        else:
            raw = "`" + b2 + "`"; kept = raw
    return raw, mk, kept


def gen_word(r, k0):
    """One word of mixed fragments: (raw, bash value, kept value, next marker number)."""
    parts, k = [], k0
    for idx in range(r.randint(1, 4)):
        t = r.random()
        if t < 0.15:
            parts.append(frag_plain(r))
        elif t < 0.3:
            ch = r.choice(PRINTABLE)
            parts.append(frag_escape(r, ch))
        elif t < 0.45:
            parts.append(frag_single(r))
        elif t < 0.6:
            parts.append(frag_double(r))
        elif t < 0.67:
            parts.append(frag_double(r, dollar=True))
        elif t < 0.82:
            parts.append(frag_ansi(r))
        elif t < 0.91:
            raw, mk, kept = frag_sub(r, k); k += 1
            parts.append((raw, mk, kept))
        else:                                  # a substitution inside "..."
            a, av = dq_body(r, 1)
            raw, mk, kept = frag_sub(r, k, in_dq=True); k += 1
            b, bv = dq_body(r, 1)
            parts.append(('"' + a + raw + b + '"', av + mk + bv, av + kept + bv))
    raw = "".join(p[0] for p in parts)
    if raw.startswith("#"):
        raw = "x" + raw; parts.insert(0, ("x", "x", "x"))
    return raw, "".join(p[1] for p in parts), "".join(p[2] for p in parts), k


def printf_cmd(parse_items):
    for c in parse_items:
        if c.kw is None and c.pos == 0:
            return c
    return None


fails, model, cases = [], [], 0


def check_line(name, words, mark=True):
    """words: [(raw, bash value, kept value)] -> compares parse() and bash."""
    global cases
    cases += 1
    line = "printf '%s\\0' " + " ".join(w[0] for w in words)
    rc, out = bash_bytes(line)
    want_bash = b"".join(as_bytes(w[1]) + b"\0" for w in words)
    if rc != 0 or out != want_bash:
        model.append("%s: generator's value disagrees with bash for %r: bash %r, model %r"
                     % (name, line, out, want_bash))
        return
    try:
        items = bash_parse.parse(line)
    except Exception as e:                     # noqa: BLE001
        fails.append("%s: parse(%r) raised %r" % (name, line, e)); return
    c = printf_cmd(items)
    got = [v for _, v in c.words[2:]] if c else None
    want = [w[2] for w in words]
    if got != want:
        fails.append("%s: line %r: parse gives values %r, bash's quote removal (substitutions kept)"
                     " gives %r" % (name, line, got, want))
    if mark:
        line2 = line + "; MARKcmd"
        try:
            names = [x.name for x in bash_parse.parse(line2) if x.kw is None]
        except Exception as e:                 # noqa: BLE001
            names = ["raised %r" % e]
        if "MARKcmd" not in names:
            fails.append("D8 %s: the command after the word is not read in %r (commands: %r)"
                         % (name, line2, names))


# ---- D1..D5 each alone ------------------------------------------------------------------------
r = random.Random(93)
for ch in PRINTABLE:
    if ch != "'":
        check_line("D1 '%r'" % ch, [frag_single(r, "a" + ch + "b")])
    check_line("D2 \\%r" % ch, [("x" + frag_escape(r, ch)[0],) + tuple("x" + v for v in frag_escape(r, ch)[1:])])
    raw = "\\" + ch
    val = ("" if ch == "\n" else ch) if ch in '$`"\\\n' else "\\" + ch
    check_line('D3 "\\%r"' % ch, [('"a' + raw + 'b"', "a" + val + "b", "a" + val + "b")])
    check_line('D3 $"\\%r"' % ch, [('$"a' + raw + 'b"', "a" + val + "b", "a" + val + "b")])
check_line("D2 backslash at end", [("ab\\", "ab\\", "ab\\")], mark=False)
for a, b in ANSI + [("\\0", "\x00"), ("\\x00", "\x00"), ("\\c@", "\x00")]:
    v = "a" + (b[:b.index("\x00")] if "\x00" in b else b + "z")
    raw = "$'a" + a + ("" if "\x00" in b else "z") + "'"
    check_line("D4 $'%s'" % a, [(raw, v, v)])
for k, body in enumerate(SUB_BODIES):
    mk = "Mk%dq" % k
    b = body.format(M=mk)
    check_line("D5 $(%s)" % b, [("a$(" + b + ")z", "a" + mk + "z", "a$(" + b + ")z")])
    check_line('D5 "$(%s)"' % b, [('"a$(' + b + ')z"', "a" + mk + "z", "a$(" + b + ")z")])
    if "`" not in b and "$(" not in b:
        b2 = b.replace("\\", "\\\\").replace("$", "\\$")
        check_line("D5 `%s`" % b, [("a`" + b2 + "`z", "a" + mk + "z", "a`" + b2 + "`z")])
        check_line('D5 "`%s`"' % b, [('"a`' + b2.replace('"', '\\"') + '`z"', "a" + mk + "z",
                                      "a`" + b2 + "`z")])

# ---- D6 mixed words, several to a line ------------------------------------------------------
r = random.Random(20261029)
for n in range(1500):
    words, k = [], 0
    for _ in range(r.randint(1, 3)):
        raw, bv, kv, k = gen_word(r, k)
        words.append((raw, bv, kv))
    check_line("D6 #%d" % n, words)

# ---- D7 code handed to eval / bash -c / sh -c -----------------------------------------------

def quote_as_one_word(r, text):
    """text spelled as one word by a random mix of quoting forms, so the word's value is text."""
    out, i = [], 0
    while i < len(text):
        j = min(len(text), i + r.randint(1, 5))
        chunk = text[i:j]; i = j
        form = r.randrange(5)
        if form == 0 and "'" not in chunk:
            out.append("'" + chunk + "'")
        elif form == 1:
            out.append('"' + "".join("\\" + c if c in '$`"\\' else c for c in chunk) + '"')
        elif form == 2:
            out.append("$'" + "".join(("\\x%02x" % ord(c)) if r.random() < 0.5 and ord(c) < 0x80
                                      else "\\'" if c == "'" else "\\\\" if c == "\\" else c
                                      for c in chunk) + "'")
        elif form == 3:
            out.append('$"' + "".join("\\" + c if c in '$`"\\' else c for c in chunk) + '"')
        else:
            out.append("".join("\\" + c if c != "\n" else "'\n'" for c in chunk))
    return "".join(out)


RUNNERS = ["eval", "bash -c", "sh -c"]
# The same builtin spelled as bash also runs it (each checked against bash below): `eval` takes
# `--` as the end of its options, and `builtin`/`command` run it, `--` or not.
SPELLINGS = ["eval --", "eval '--'", "eval \\-\\-", "builtin eval", "command eval", "builtin -- eval",
             "command -- eval", "builtin eval --", "'eval' --", "A=1 eval --", "bash -c --",
             "true && eval --", "{ eval -- %s; }"]


def handed(n, runner, line, code, want):
    """line must hand on exactly code, and bash must run line as it runs code."""
    global cases
    cases += 1
    rc, out = bash_bytes(line)
    if not runner.startswith("sh -c") and (rc, out) != want:
        model.append("D7 #%s %s: bash runs %r differently from its code %r" % (n, runner, line, code))
        return
    try:
        got = [c2 for c in bash_parse.parse(line) for c2 in c.codes]
    except Exception as e:                     # noqa: BLE001
        fails.append("D7 #%s %s: parse(%r) raised %r" % (n, runner, line, e)); return
    if code not in got:
        fails.append("D7 #%s %s: line %r hands on %r, where bash runs %r (exit %d, output %r)"
                     % (n, runner, line, got, code, rc, out))


def place(runner, w):
    return runner % w if "%s" in runner else runner + " " + w


r = random.Random(5)
for n in range(400):
    words, k = [], 0
    for _ in range(r.randint(1, 3)):
        raw, bv, kv, k = gen_word(r, k)
        words.append((raw, bv, kv))
    head, rest = "printf '%s\\0'", " ".join(w[0] for w in words)
    code = head + " " + rest
    w = quote_as_one_word(r, code)
    want = bash_bytes(code)
    for runner in RUNNERS + (SPELLINGS if n < 20 else [r.choice(SPELLINGS)]):
        handed(n, runner, place(runner, w), code, want)
    # several words: eval joins their values with a space (D7b)
    if n % 4 == 0:
        handed("%d words" % n, "eval", "eval " + quote_as_one_word(r, head) + " "
               + quote_as_one_word(r, rest), code, want)

# ---- D9 a word with no quote and no backslash is its own value ---------------------------------
# Quote removal changes nothing in such a word, whatever expansions it holds, and the word ends
# where bash's word ends: what follows it on the line is this command's words, not a command.
EXP = ["$((1+2))", "$(( 2 * 3 ))", "$((1))$((2))", "$[1+2]", "${x:-a}", "$x", "${#x}", "$((1+$(printf 4)))",
       "$(( $(printf 5) ))", "${x:-$(printf q)}", "$((x=1,x+1))", "$@", "$1"]
r = random.Random(9)
for n, e in enumerate(EXP * 3):
    pre = r.choice(["a", "z9_", "Q"])
    post = r.choice(["", "b", "-c", "=d"])
    raw = pre + e + post
    line = "printf '%s\\0' " + raw + " w2 w3; MARKcmd"
    cases += 1
    rc, out = bash_bytes("MARKcmd(){ :; }\n" + line)
    if rc != 0 or out.count(b"\0") != 3:
        model.append("D9 %r: bash does not read it as one word before w2 w3 (%d, %r)" % (raw, rc, out))
        continue
    try:
        items = bash_parse.parse(line)
    except Exception as ex:                    # noqa: BLE001
        fails.append("D9 %r: parse raised %r" % (line, ex)); continue
    c = printf_cmd(items)
    got = [v for _, v in c.words[2:]] if c else None
    if got != [raw, "w2", "w3"]:
        fails.append("D9 %r: parse gives the printf the values %r, where the words are %r"
                     % (line, got, [raw, "w2", "w3"]))
    extra = sorted({x.name for x in items if x.kw is None} - {"printf", "MARKcmd"})
    if extra:
        fails.append("D9 %r: parse reads commands %r that bash does not run as commands of this line"
                     % (line, extra))

import re as _re
groups = {}
for f in fails:
    groups.setdefault(_re.sub(r" #\S+( words)?", "", f.split(": ", 1)[0]), []).append(f)
print("cases: %d; parser disagreements: %d; generator faults: %d" % (cases, len(fails), len(model)))
for f in model[:40]:
    print("  MODEL " + f)
for g in sorted(groups):
    print("%-40s %d disagreement(s)" % (g, len(groups[g])))
    for f in groups[g][:4]:
        print("  FAIL " + f)
sys.exit(1 if fails or model or cases == 0 else 0)
