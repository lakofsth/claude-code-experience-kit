def refused(cmd):
    p = subprocess.run(["bash", HOOK],
                       input=json.dumps({"tool_name": "Bash", "tool_input": {"command": cmd}}),
                       capture_output=True, text=True)
    if p.returncode not in (0, 2):
        return None, "hook exited %d: %s" % (p.returncode, p.stderr.strip()[:200])
    return p.returncode == 2 and "BLOCKED" in p.stderr, ""


bad = []
for group, rows, want in (("held", MUST_REFUSE_HELD, True), ("new", MUST_REFUSE_NEW, True),
                          ("silent", MUST_STAY_SILENT, False)):
    for cmd in rows:
        got, err = refused(cmd)
        ok = got is want
        print("%s %-6s %s %s" % ("ok  " if ok else "FAIL", group,
                                 "refused" if got else ("silent " if got is False else "error  "), cmd))
        if not ok:
            bad.append((group, cmd, err))

n = len(MUST_REFUSE_HELD) + len(MUST_REFUSE_NEW) + len(MUST_STAY_SILENT)
print("cases: %d (%d held, %d new must-refuse, %d must-stay-silent); failed %d"
      % (n, len(MUST_REFUSE_HELD), len(MUST_REFUSE_NEW), len(MUST_STAY_SILENT), len(bad)))
for g, c, e in bad:
    print("  FAILED [%s] %s %s" % (g, c, e))
sys.exit(1 if bad else 0)
